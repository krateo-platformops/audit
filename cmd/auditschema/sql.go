// impossibleKey is a key no writer writes: its missing count must equal rows
// in every group, or the query is not reading what it claims to.
const impossibleKey = "claude.no.such.key"

const table = "default.krateo_audit"

const window = "Timestamp >= {start:DateTime64(9)} AND Timestamp < {end:DateTime64(9)}"

// conditionSQL is each checker condition as a ClickHouse predicate on one
// row. TestConditionSQLIsTotal fails when the schema gains a condition this
// map does not name.
var conditionSQL = map[audit.Condition]string{
	audit.CondK8sTarget:        k8sTargetSQL,
	audit.CondMethodOther:      "(" + attr(audit.KeyHTTPMethod) + " = '_OTHER')",
	audit.CondWrite:            attr(audit.KeyVerb) + " IN " + inList(audit.WriteVerbs()),
	audit.CondDelegated:        "(" + attr(audit.KeyDelegation) + " != '' OR " + attr(audit.KeyOnBehalfOf) + " != '')",
	audit.CondImpersonated:     "(" + attr(audit.KeyImpersonatedUser) + " != '' OR " + attr(audit.KeyImpersonatedRoles) + " != '')",
	audit.CondCaused:           "arrayExists(k -> startsWith(k, 'krateo.audit.cause_ref.'), mapKeys(LogAttributes))",
	audit.CondDenied:           "(" + attr(audit.KeyOutcome) + " = " + lit(audit.OutcomeDenied) + ")",
	audit.CondContentWrite:     attr(audit.KeyVerb) + " IN " + inList(audit.ContentWriteVerbs()),
	audit.CondClientRejected:   "(" + attr(audit.KeyClientRejected) + " != '')",
	audit.CondClientProvenance: clientProvenanceSQL(),
	audit.CondConfirmedSet:     "arrayExists(k -> startsWith(k, 'krateo.audit.client.confirmed_set.'), mapKeys(LogAttributes))",
}

var k8sTargetSQL = "(" + attr(audit.KeyNamespace) + " != '' OR arrayExists(k -> startsWith(k, 'krateo.audit.object_ref.'), mapKeys(LogAttributes)))"

// clientProvenanceSQL is condition client_provenance: any client key other
// than source and rejected, each named, as the schema lists them.
func clientProvenanceSQL() string {
	var ors []string
	for _, k := range audit.Keys() {
		if strings.HasPrefix(k.Name, "krateo.audit.client.") && k.Name != audit.KeyClientSource && k.Name != audit.KeyClientRejected {
			ors = append(ors, attr(k.Name)+" != ''")
		}
	}
	return "(" + strings.Join(ors, " OR ") + ")"
}

// credentialTargetSQL is the record's object_ref naming a credential target.
func credentialTargetSQL() string {
	var ors []string
	for _, c := range audit.CredentialTargets() {
		p := attr(audit.KeyObjectAPIGroup) + " = " + lit(c.Group) + " AND " + attr(audit.KeyObjectResource) + " = " + lit(c.Resource)
		if c.Subresource != "" {
			p += " AND " + attr(audit.KeyObjectSubresource) + " = " + lit(c.Subresource)
		}
		ors = append(ors, "("+p+")")
	}
	return "(" + strings.Join(ors, " OR ") + ")"
}

func attr(k string) string { return "LogAttributes[" + lit(k) + "]" }

func lit(s string) string { return "'" + strings.ReplaceAll(s, "'", `\'`) + "'" }

func lits(ss []string) string {
	q := make([]string, len(ss))
	for i, s := range ss {
		q[i] = lit(s)
	}
	return "[" + strings.Join(q, ", ") + "]"
}

var nonAlnum = regexp.MustCompile(`[^a-z0-9]+`)

func alias(prefix, key string) string { return prefix + "_" + nonAlnum.ReplaceAllString(key, "_") }

func marked(marker string) string {
	return "has(splitByChar(',', " + attr(audit.KeyIncomplete) + "), " + lit(marker) + ")"
}

// conformanceSQL is every query, in order: required keys per writer, rules
// per writer, leak detector.
func conformanceSQL() string {
	var b strings.Builder
	fmt.Fprintf(&b, "-- Live conformance of %s against audit schema %s, generated by\n", table, audit.SchemaVersion)
	b.WriteString("-- `auditschema sql` from schema/v1.yaml. Run each with --param_start and\n")
	b.WriteString("-- --param_end. Read-only.\n")
	b.WriteString("--\n-- Denominator: rows > 0 for every population expected in the window. Zero\n")
	b.WriteString("-- rows is not conformance.\n\n")
	for _, w := range audit.Writers() {
		if scopes := scopesOf(w, false); len(scopes) > 0 {
			b.WriteString(requiredSQL(w))
			b.WriteString(rulesSQL(w))
		}
	}
	b.WriteString(leakSQL())
	return b.String()
}

// scopesOf returns writer w's scope names, with its legacy controls when
// legacy is true.
func scopesOf(w audit.Writer, legacy bool) []string {
	var out []string
	for _, p := range audit.Populations() {
		if p.Writer == w {
			out = append(out, p.Scope)
		}
	}
	if legacy {
		for _, p := range audit.LegacyControls() {
			if p.Writer == w {
				out = append(out, p.Scope)
			}
		}
	}
	return out
}

// requiredSQL counts, per population x schema x class x key, the rows that
// lack each key writer w must always write.
func requiredSQL(w audit.Writer) string {
	var keys, markers []string
	for _, k := range audit.Keys() {
		r := k.Writers[w]
		if r.Level == audit.LevelRequired || r.Level == audit.LevelConditional && r.Check == "" && r.Markable {
			keys = append(keys, k.Name)
			m := ""
			if r.Markable {
				m = k.Marker
			}
			markers = append(markers, m)
		}
	}
	keys, markers = append(keys, impossibleKey), append(markers, "")

	var b strings.Builder
	fmt.Fprintf(&b, "-- Required keys, writer %s.\n", w)
	b.WriteString("-- Pass, in every group with schema = '1': missing_unmarked = 0 for every real\n")
	b.WriteString("-- key (missing counts the rows marked incomplete for it too).\n")
	fmt.Fprintf(&b, "-- Impossible-key control: %s has missing = rows in every group.\n", impossibleKey)
	if legacy := scopesOf(w, true)[len(scopesOf(w, false)):]; len(legacy) > 0 {
		fmt.Fprintf(&b, "-- Positive control: the legacy scope(s) %s (schema = '') have\n", strings.Join(legacy, ", "))
		fmt.Fprintf(&b, "-- %s missing = rows. It lapses when those rows expire.\n", audit.KeyEventName)
	}
	fmt.Fprintf(&b, "WITH %s AS required_keys,\n     %s AS required_markers\n", lits(keys), lits(markers))
	b.WriteString("SELECT ScopeName, ServiceName,\n")
	fmt.Fprintf(&b, "       %s AS schema,\n", attr(audit.KeySchemaVersion))
	fmt.Fprintf(&b, "       %s AS actor_class,\n", attr(audit.KeyActorClass))
	b.WriteString("       key,\n       count() AS rows,\n")
	b.WriteString("       countIf(LogAttributes[key] = '') AS missing,\n")
	fmt.Fprintf(&b, "       countIf(LogAttributes[key] = '' AND (marker = '' OR NOT has(splitByChar(',', %s), marker))) AS missing_unmarked\n", attr(audit.KeyIncomplete))
	fmt.Fprintf(&b, "FROM %s\n", table)
	b.WriteString("ARRAY JOIN required_keys AS key, required_markers AS marker\n")
	fmt.Fprintf(&b, "WHERE %s\n  AND ScopeName IN %s\n", window, inList(scopesOf(w, true)))
	b.WriteString("GROUP BY ScopeName, ServiceName, schema, actor_class, key\n")
	b.WriteString("ORDER BY ScopeName, ServiceName, schema, actor_class, key;\n\n")
	return b.String()
}

// rulesSQL counts, per population, the schema-1 rows of writer w that break
// a conditional key, an enum, the closed set, the target rule or a W1 pair.
func rulesSQL(w audit.Writer) string {
	var cols []string
	add := func(name, pred string) { cols = append(cols, fmt.Sprintf("  countIf(%s) AS %s", pred, name)) }

	target := audit.Target()
	var none, all []string
	for _, k := range target.Keys {
		none = append(none, attr(k)+" = ''")
		all = append(all, attr(k)+" != ''")
	}
	add("no_target", strings.Join(none, " AND ")+" AND NOT "+marked(target.Marker))
	add("target_marked_incomplete", strings.Join(none, " AND ")+" AND "+marked(target.Marker))
	if target.Writers[w] == audit.TargetExactlyOne {
		add("two_targets", strings.Join(all, " AND "))
	}

	var allKeys, notForWriter []string
	for _, k := range audit.Keys() {
		allKeys = append(allKeys, k.Name)
		r := k.Writers[w]
		if r.Level <= audit.LevelNotEstablished {
			notForWriter = append(notForWriter, k.Name)
			continue
		}
		if r.Level == audit.LevelConditional && r.Check != "" {
			pred := conditionSQL[r.Check] + " AND " + attr(k.Name) + " = ''"
			if r.Markable {
				pred += " AND NOT " + marked(k.Marker)
			}
			add(alias("unmet", k.Name), pred)
		}
		switch {
		case k.OnlyWhen != "" && k.NotWhen != "":
			add(alias("unexpected", k.Name), attr(k.Name)+" != '' AND (NOT "+conditionSQL[k.OnlyWhen]+" OR "+conditionSQL[k.NotWhen]+")")
		case k.OnlyWhen != "":
			add(alias("unexpected", k.Name), attr(k.Name)+" != '' AND NOT "+conditionSQL[k.OnlyWhen])
		case k.NotWhen != "":
			add(alias("unexpected", k.Name), attr(k.Name)+" != '' AND "+conditionSQL[k.NotWhen])
		}
		if k.CredentialFree {
			add(alias("not_for_target", k.Name), attr(k.Name)+" != '' AND "+credentialTargetSQL())
		}
		// The key's enum, or this writer's own closed set: one of them, never
		// both (schemagen refuses a key with both).
		if vs := append(slices.Clone(k.Values), r.Values...); len(vs) > 0 {
			add(alias("bad", k.Name), attr(k.Name)+" NOT IN ("+strings.Join(append([]string{"''"}, quoted(vs)...), ", ")+")")
		}
	}
	add("not_in_schema", "arrayExists(k -> NOT has("+lits(allKeys)+", k), mapKeys(LogAttributes))")
	if len(notForWriter) > 0 {
		add("not_for_writer", "arrayExists(k -> has("+lits(notForWriter)+", k), mapKeys(LogAttributes))")
	}

	var disagree, orphan []string
	for _, k := range audit.Keys() {
		if k.ReplacedBy == "" {
			continue
		}
		disagree = append(disagree, "("+attr(k.Name)+" != '' AND "+attr(k.Name)+" != "+attr(k.ReplacedBy)+")")
		orphan = append(orphan, "("+attr(k.Name)+" != '' AND "+attr(k.ReplacedBy)+" = '')")
	}
	add("w1_legacy_disagrees", strings.Join(disagree, " OR "))
	add("w1_legacy_without_replacement", strings.Join(orphan, " OR "))
	add("affected_user_is_actor", attr(audit.KeyAffectedUser)+" != '' AND "+attr(audit.KeyAffectedUser)+" = "+attr(audit.KeyUserName))

	var b strings.Builder
	fmt.Fprintf(&b, "-- Conditional keys, enums, closed set, target rule and W1 pairs, writer %s.\n", w)
	b.WriteString("-- Pass: every column after rows is 0 (target_marked_incomplete counts honest\n")
	b.WriteString("-- gaps, reported apart).\n")
	b.WriteString("SELECT ScopeName, ServiceName, count() AS rows,\n")
	b.WriteString(strings.Join(cols, ",\n"))
	fmt.Fprintf(&b, "\nFROM %s\n", table)
	fmt.Fprintf(&b, "WHERE %s\n", window)
	fmt.Fprintf(&b, "  AND %s = %s AND %s = %s\n", attr(audit.KeyEventName), lit(audit.EventName), attr(audit.KeySchemaVersion), lit(audit.SchemaVersion))
	fmt.Fprintf(&b, "  AND ScopeName IN %s\n", inList(scopesOf(w, false)))
	b.WriteString("GROUP BY ScopeName, ServiceName\nORDER BY ScopeName, ServiceName;\n\n")
	return b.String()
}

// leakSQL is the detector for an identity key outside the audit table, with
// its positive control (the audit table itself) and its impossible-key
// control.
func leakSQL() string {
	var identity []string
	for _, k := range audit.Keys() {
		if k.Identity {
			identity = append(identity, k.Name)
		}
	}
	q := func(keys []string) string {
		k := lits(keys)
		return "SELECT 'otel_traces' AS tbl, count() AS rows FROM default.otel_traces\n" +
			" WHERE Timestamp > now() - INTERVAL 7 DAY AND hasAny(mapKeys(SpanAttributes), " + k + ")\n" +
			"UNION ALL\n" +
			"SELECT 'otel_logs', count() FROM default.otel_logs\n" +
			" WHERE Timestamp > now() - INTERVAL 7 DAY AND hasAny(mapKeys(LogAttributes), " + k + ")\n" +
			"UNION ALL\n" +
			"SELECT 'krateo_audit (positive control)', count() FROM " + table + "\n" +
			" WHERE Timestamp > now() - INTERVAL 30 DAY AND hasAny(mapKeys(LogAttributes), " + k + ");\n"
	}
	var b strings.Builder
	b.WriteString("-- Leak detector: no identity-bearing audit key on a span or an ordinary log.\n")
	b.WriteString("-- Pass: otel_traces = 0, otel_logs = 0, krateo_audit > 0.\n")
	b.WriteString(q(identity))
	fmt.Fprintf(&b, "\n-- Its control, with only %s: all three are 0.\n", impossibleKey)
	b.WriteString(q([]string{impossibleKey}))
	return b.String()
}

func quoted(ss []string) []string {
	out := make([]string, len(ss))
	for i, s := range ss {
		out[i] = lit(s)
	}
	return out
}

func inList(ss []string) string { return "(" + strings.Join(quoted(ss), ", ") + ")" }
